use std::fs;
use std::path::Path;

use ts_rs::{Config, TS};

fn make_field_optional(source: &mut String, type_name: &str, field_name: &str) {
    let declaration = format!("export type {type_name} = {{");
    let start = source.find(&declaration).unwrap_or_else(|| panic!("missing generated type {type_name}"));
    let end = start + source[start..].find("};").unwrap_or_else(|| panic!("unterminated generated type {type_name}"));
    let field = format!("{field_name}: ");
    let offset =
        source[start..end].find(&field).unwrap_or_else(|| panic!("missing generated field {type_name}.{field_name}"));
    source.insert(start + offset + field_name.len(), '?');
}

