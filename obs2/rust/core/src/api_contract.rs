    export!(ge_catalog::YoutubeAssociationSource);
    export!(ge_catalog::YoutubeMetadata);
    export!(ge_catalog::UploadHistoryEntry);
    export!(ge_catalog::statistics::StatusCounts);
    export!(ge_catalog::statistics::StatisticsRange);
    export!(ge_catalog::statistics::DifficultyCombinedBest);
    export!(ge_catalog::statistics::CombinedBestTimes);
    export!(ge_catalog::statistics::StatisticsSummary);
    export!(ge_catalog::statistics::LevelDifficultyCounts);
    export!(ge_catalog::statistics::LevelCounts);
