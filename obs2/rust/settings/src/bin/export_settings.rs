use std::path::PathBuf;
use std::{env, fs};

use ge_settings::{AppSettings, MAX_RECENT_RUN_LIMIT, MonitorDesign, UpdateCheckInterval, YoutubeVisibility};
use serde_json::Value;
use ts_rs::{Config, TS};

fn main() {
    let output = env::args_os().nth(1).map(PathBuf::from).expect("usage: export-settings <output.ts>");
    let mut defaults = serde_json::to_value(AppSettings::default()).expect("serialize default settings");
    let object = defaults.as_object_mut().expect("settings defaults should be an object");
    object.remove("lastKnownUpdateVersion");
    object.remove("lastKnownUpdateReleaseUrl");
    let config = Config::default();

    let source = format!(
        "// Generated by ge_settings. Do not edit.\n\n{}\n\n{}\n\n{}\n\n{}\n\nexport const MAX_RECENT_RUN_LIMIT = {MAX_RECENT_RUN_LIMIT};\n\nexport const DEFAULT_SETTINGS: AppSettings = {};\n",
        exported(MonitorDesign::decl(&config)),
        exported(UpdateCheckInterval::decl(&config)),
        exported(YoutubeVisibility::decl(&config)),
        exported(AppSettings::decl(&config)),
        pretty_json(defaults),
    );

    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).expect("create generated settings directory");
    }
    fs::write(output, source).expect("write generated settings bindings");
}

fn exported(declaration: String) -> String {
    format!("export {declaration}")
}

fn pretty_json(value: Value) -> String {
    serde_json::to_string_pretty(&value).expect("serialize TypeScript defaults")
}
